def sha256_16(path: Path) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()[:16]


def run_stage(num: int, script: str, desc: str) -> tuple[bool, float]:
    log.info("=== Stage %d: %s -- %s ===", num, script, desc)
    t0 = time.time()
    log_path = REV3 / f"_run_all_stage{num:02d}.log"
    with open(log_path, "w") as lf:
        r = subprocess.run([PY, str(REV3 / script)], stdout=lf, stderr=subprocess.STDOUT)
    elapsed = time.time() - t0
    ok = r.returncode == 0
    status = "OK" if ok else f"FAILED (exit {r.returncode})"
    log.info("  Stage %d %s in %.1fs (log: %s)", num, status, elapsed, log_path.name)
    if not ok:
        tail = log_path.read_text().splitlines()[-25:]
        log.error("  Last 25 lines of stage %d log:\n%s", num, "\n".join(tail))
    return ok, elapsed


def run_tests() -> bool:
    log.info("=== Test suite: tests/test_identity_range.py ===")
    r = subprocess.run([PY, "-m", "pytest", str(REV3 / "tests" / "test_identity_range.py"), "-v"],
                        capture_output=True, text=True)
    print(r.stdout[-3000:])
    ok = r.returncode == 0
    log.info("  Test suite %s", "PASSED" if ok else "FAILED")
    return ok


def rebuild_manifest() -> None:
    log.info("=== Rebuilding output_manifest.csv from scratch ===")
    rows = []
    for relpath, producer, desc in KNOWN_OUTPUTS:
        p = cfg.PROJECT_ROOT / relpath
        if not p.exists():
            rows.append({"path": relpath, "producer_script": producer, "description": desc,
                         "size_bytes": None, "shape": "MISSING", "sha256_16": None})
            continue
        shape = "n/a"
        if p.suffix == ".parquet":
            try:
                shape = f"{pd.read_parquet(p).shape[0]} rows x {pd.read_parquet(p).shape[1]} cols"
            except Exception:
                shape = "n/a (unreadable)"
        elif p.suffix == ".csv":
            try:
                df = pd.read_csv(p)
                shape = f"{df.shape[0]} rows x {df.shape[1]} cols"
            except Exception:
                shape = "n/a (unreadable)"
        size = p.stat().st_size
        checksum = sha256_16(p) if size < 500_000_000 else "skipped (large file, see provenance json)"
        rows.append({"path": relpath, "producer_script": producer, "description": desc,
                     "size_bytes": size, "shape": shape, "sha256_16": checksum})
    manifest = pd.DataFrame(rows)
    manifest.to_csv(REV3 / "output_manifest.csv", index=False)
    n_missing = int((manifest["shape"] == "MISSING").sum())
    log.info("  Manifest: %d files tracked, %d missing", len(manifest), n_missing)
    if n_missing:
        log.warning("  Missing files:\n%s", manifest[manifest.shape == "MISSING"][["path"]].to_string(index=False))


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--from", dest="from_stage", type=int, default=1, help="Resume from this stage number")
    ap.add_argument("--only", type=int, default=None, help="Run only this stage number")
    ap.add_argument("--skip-tests", action="store_true", help="Skip the pytest stage")
    ap.add_argument("--skip-facts", action="store_true", help="Skip rebuilding facts.json")
    args = ap.parse_args()

    t0 = time.time()
    stages_to_run = [s for s in STAGES if s[0] == args.only] if args.only else \
                     [s for s in STAGES if s[0] >= args.from_stage]

    results = []
    for num, script, desc in stages_to_run:
        ok, elapsed = run_stage(num, script, desc)
        results.append({"stage": num, "script": script, "ok": ok, "elapsed_s": round(elapsed, 1)})
        if not ok:
            log.error("Pipeline stopped at stage %d (%s). Fix and re-run with --from %d.", num, script, num)
            print(json.dumps(results, indent=2))
            sys.exit(1)

    tests_ok = True
    if not args.skip_tests:
        tests_ok = run_tests()

    if not args.skip_facts:
        log.info("=== Rebuilding facts.json ===")
        r = subprocess.run([PY, str(REV3 / "build_facts_json.py")], capture_output=True, text=True)
        if r.returncode != 0:
            log.error("build_facts_json.py failed:\n%s", r.stderr[-2000:])
        else:
            log.info("  facts.json rebuilt.")

    rebuild_manifest()

    total = time.time() - t0
    log.info("=== Pipeline complete in %.1fs ===", total)
    log.info("Stages run: %s", [(r["stage"], "OK" if r["ok"] else "FAIL") for r in results])
    log.info("Test suite: %s", "PASSED" if tests_ok else "FAILED (see above)")
    log.info("See scripts/revision_v3/audit_report.md for the human-readable narrative "
              "(not regenerated by this script -- manually maintained).")
    if not tests_ok:
        sys.exit(1)


if __name__ == "__main__":
    main()
