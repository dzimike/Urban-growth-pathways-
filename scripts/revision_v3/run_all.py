"""
Paper 2 v3 -- One-command pipeline (Requirement 13)

Runs scripts 01-07 in order, then the identity/range test suite, then
rebuilds facts.json and output_manifest.csv from scratch (not by
incremental append, to avoid any accumulated inconsistency from
interactive development).

Design notes
------------
- Each stage is run as a SEPARATE subprocess (python3 <script>.py), not
  imported and called in-process. This is deliberate: several stages set
  process environment variables for GDAL/PROJ (see config.QGIS_GDAL_ENV)
  and this keeps that scoped per-subprocess rather than leaking between
  stages or depending on import order.
- Idempotency is handled INSIDE each stage, not here: script 01 already
  skips tiles it has already downloaded; scripts 02-07 are cheap enough
  (33s-73s each) that simply re-running them is simpler and safer than
  adding a second layer of skip-logic here that could drift out of sync
  with what each script actually checks.
- audit_report.md is NOT regenerated by this script. It is a manually
  curated narrative document (investigative write-ups of findings like
  the ANBH quantization spike, the disconnected-components investigation,
  the GM_Error residual bug-and-fix) that is not purely mechanically
  derivable from script output. This is a deliberate scope boundary, not
  an oversight: run_all.py's job is the ANALYTICAL pipeline + machine-
  readable facts.json + file manifest; audit_report.md is the
  human-readable companion, maintained alongside it.
- Per Requirement 14, no manuscript text exists yet and this script does
  not produce any -- it stops at facts.json/output_manifest.csv.

Usage
-----
    python scripts/revision_v3/run_all.py                  # full pipeline
    python scripts/revision_v3/run_all.py --from 4          # resume from script 04
    python scripts/revision_v3/run_all.py --only 6          # re-run just script 06
    python scripts/revision_v3/run_all.py --skip-tests      # skip pytest stage
"""
